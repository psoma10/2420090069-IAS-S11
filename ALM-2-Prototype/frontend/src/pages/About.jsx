function ZCalc() {
  const [x, setX] = useState(38)
  const [mean, setMean] = useState(20)
  const [std, setStd] = useState(4)
  const [sigma, setSigma] = useState(3)
  const s = Math.max(std, 0.001)
  const z = (x - mean) / s
  const thr = mean + sigma * s
  const anomalous = z > sigma
  const num = (set) => (e) => set(Number(e.target.value))
  return (
    <div className="ab-zcalc">
      <div className="ab-zform">
        <label>Observed x<input type="number" value={x} onChange={num(setX)} /></label>
        <label>Mean<input type="number" value={mean} onChange={num(setMean)} /></label>
        <label>Std dev<input type="number" min="0" step="0.5" value={std} onChange={num(setStd)} /></label>
        <label>Sigma<input type="number" min="1" max="6" step="0.5" value={sigma} onChange={num(setSigma)} /></label>
      </div>
      <div className={`ab-zres ${anomalous ? 'is-bad' : 'is-ok'}`} role="status">
        <div className="mono">z = ({x} - {mean}) / {s} = <b>{z.toFixed(2)}</b></div>
        <div className="mono">threshold = {mean} + {sigma} x {s} = <b>{thr.toFixed(1)}</b></div>
        <div>{anomalous ? <Badge tone="high" dot>ANOMALY: z exceeds sigma</Badge> : <Badge tone="allow" dot>Normal: within sigma</Badge>}</div>
      </div>
    </div>
  )
}

